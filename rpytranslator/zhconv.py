_TRAD_TO_SIMP: dict[str, str] = {}
for _seg in _TABLE.split():
    if len(_seg) != 2:
        raise ValueError(f"对照段必须是「繁简」两字: {_seg!r}")
    _t, _s = _seg[0], _seg[1]
    if _t == _s:
        raise ValueError(f"不允许同形字对（会误判为繁体）: {_t!r}")
    _TRAD_TO_SIMP[_t] = _s
del _seg, _t, _s


def traditional_chars(text: str) -> list[str]:
    """返回文本里出现的繁体字（去重、保持出现顺序）。"""
    out: list[str] = []
    seen: set[str] = set()
    for ch in text:
        if ch in _TRAD_TO_SIMP and ch not in seen:
            seen.add(ch)
            out.append(ch)
    return out


def has_traditional(text: str) -> bool:
    """文本是否含繁体字形。"""
    if not text:
        return False
    return any(ch in _TRAD_TO_SIMP for ch in text)


def to_simplified(text: str) -> str:
    """把文本里的繁体字形换成简体（逐字替换；标点、空格、占位符不动）。"""
    if not text:
        return text
    return "".join(_TRAD_TO_SIMP.get(ch, ch) for ch in text)
